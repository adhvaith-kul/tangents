"use client";
// Where a story came from: the provenance badge on every node, and the "How
// this story came about" panel that opens under a row when its title is clicked.
// Links to real articles are the only links in the app that leave it; they open
// in a new browser tab and say where they go.
import Link from "next/link";
import type { ReactNode } from "react";
import type { Provenance, RealHeadline, StoryMapStoryline } from "@/lib/types";

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

const BADGE: Record<Provenance, { label: string; title: string; tone: string }> = {
  real: {
    label: "Real Seed",
    title: "Seeded by an actual news headline. Narrative, reactions, and articles are AI simulation.",
    tone: "border-x-blue/40 text-x-blue bg-x-blue/10",
  },
  adapted: {
    label: "Adapted Seed",
    title: "A real news headline adapted to fit the simulation. Narrative is AI fiction.",
    tone: "border-x-gold/40 text-x-gold bg-x-gold/10",
  },
  invented: {
    label: "AI Invented",
    title: "No real source: storyline and events are fully generated by AI simulation.",
    tone: "border-x-border text-x-dim bg-x-hover/30",
  },
  yours: {
    label: "Your Prompt",
    title: "Triggered by your custom What If prompt or post.",
    tone: "border-x-pink/40 text-x-pink bg-x-pink/10",
  },
};

export function ProvenanceBadge({ provenance }: { provenance: Provenance }) {
  const b = BADGE[provenance];
  return (
    <span title={b.title} className={`rounded border px-1.5 py-0.5 text-[11px] font-bold leading-[14px] ${b.tone}`}>
      {b.label}
    </span>
  );
}

/** "12 stories: 9 seeded from real news, 1 adapted, 1 invented, 1 yours." */
export function provenanceSummary(storylines: StoryMapStoryline[]): string {
  const n = (p: Provenance) => storylines.filter((s) => s.provenance === p).length;
  const total = storylines.length;
  return `${total} ${total === 1 ? "story" : "stories"}: ${n("real")} seeded from real news, ${n("adapted")} adapted, ${n("invented")} AI-invented, ${n("yours")} yours.`;
}

function hostOf(link: string): string | null {
  try {
    return new URL(link).hostname.replace(/^www\./, "");
  } catch {
    return null;
  }
}

function dateOf(t: number): string {
  const d = new Date(t);
  return `${MONTHS[d.getMonth()]} ${d.getDate()}, ${d.getFullYear()}`;
}

/** The arrow that marks a link out of the app. */
function ExternalMark() {
  return (
    <svg viewBox="0 0 24 24" width={12} height={12} aria-hidden className="inline-block shrink-0 align-[-1px]">
      <path
        d="M14 4h6v6M20 4l-9 9M18 14v5a1 1 0 0 1-1 1H5a1 1 0 0 1-1-1V7a1 1 0 0 1 1-1h5"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

function Headline({ h, tag }: { h: RealHeadline; tag?: string }) {
  const host = h.link ? hostOf(h.link) : null;
  const meta = [h.source, h.publishedAt != null ? dateOf(h.publishedAt) : null, tag].filter(Boolean).join(" · ");
  return (
    <div className="rounded-lg border border-x-border/80 bg-x-bg/60 p-3">
      <div className="flex items-center gap-1.5 text-[11px] font-bold uppercase tracking-wider text-x-blue">
        <span className="h-2 w-2 rounded-full bg-x-blue" />
        {h.adapted ? "Original Real Headline" : "Real-World News Wire"}
      </div>
      <p className="mt-1 text-[14px] font-medium leading-5 text-x-text">"{h.title}"</p>
      <div className="mt-1.5 flex flex-wrap items-center gap-x-1.5 text-[12px] leading-4 text-x-dim">
        <span>{meta}</span>
        {h.link ? (
          <>
            <span aria-hidden>·</span>
            <a
              href={h.link}
              target="_blank"
              rel="noopener noreferrer"
              title="Opens the real article in a new browser tab"
              className="inline-flex items-center gap-1 font-semibold text-x-blue hover:underline"
            >
              Verify source ({host ?? "external article"})
              <ExternalMark />
            </a>
          </>
        ) : null}
      </div>
      {h.adapted ? (
        <div className="mt-2.5 border-t border-x-border/60 pt-2">
          <div className="text-[11px] font-bold uppercase tracking-wider text-x-gold">Adapted for this world</div>
          <p className="mt-0.5 text-[13px] leading-5 text-x-text">{h.adapted}</p>
        </div>
      ) : null}
    </div>
  );
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <div className="mt-3">
      <div className="mb-1 text-[13px] font-bold leading-4 text-x-dim">{title}</div>
      {children}
    </div>
  );
}

function StoryLink({ story, onJump }: { story: { id: number; title: string }; onJump: (id: number) => void }) {
  return (
    <button
      type="button"
      onClick={() => onJump(story.id)}
      className="block text-left text-[15px] leading-5 text-x-blue hover:underline"
    >
      {story.title}
    </button>
  );
}

export function StoryBackgroundPanel({ storyline, onJump }: { storyline: StoryMapStoryline; onJump: (id: number) => void }) {
  const { started, parent, spinoffs, drewOn, facts } = storyline.background;
  return (
    <div
      className="mt-3 cursor-default rounded-2xl border border-x-border bg-x-card/50 px-4 pb-4 pt-3"
      onClick={(e) => e.stopPropagation()}
    >
      <div className="text-[15px] font-bold leading-5 text-x-text">How this story came about</div>
      <div className="mt-1.5 flex items-start gap-2 rounded-lg border border-x-border/70 bg-x-hover/30 p-2.5 text-[12px] leading-4 text-x-dim">
        <span className="text-base select-none">ℹ️</span>
        <span>
          <strong className="text-x-text">Real vs. AI Simulated:</strong> Real headlines serve only as initial inspiration seeds. All downstream storyline events, tweets, character posts, news articles, and stock movements are generative AI satire.
        </span>
      </div>
      <Section title="Started from">
        {started.kind === "headline" ? (
          started.headline ? (
            <Headline h={started.headline} />
          ) : (
            <p className="text-[15px] leading-5 text-x-text">A real headline that is no longer on file.</p>
          )
        ) : started.kind === "whatif" ? (
          <>
            <p className="text-[15px] leading-5 text-x-text">Your What if</p>
            {/* The premise itself is not kept; this is how the world opened the story. */}
            {started.text ? <p className="mt-0.5 text-[13px] leading-4 text-x-dim">{started.text}</p> : null}
          </>
        ) : started.kind === "post" ? (
          <Link href={`/post/${started.postId}`} className="text-[15px] leading-5 text-x-blue hover:underline">
            Your post
          </Link>
        ) : (
          <p className="text-[15px] leading-5 text-x-text">Invented by the world</p>
        )}
      </Section>
      {parent ? (
        <Section title="Grew out of">
          <StoryLink story={parent} onJump={onJump} />
        </Section>
      ) : null}
      {spinoffs.length > 0 ? (
        <Section title="Led to">
          <div className="space-y-1">
            {spinoffs.map((s) => (
              <StoryLink key={s.id} story={s} onJump={onJump} />
            ))}
          </div>
        </Section>
      ) : null}
      {drewOn.length > 0 ? (
        <Section title="Also drew on">
          <div className="space-y-3">
            {drewOn.map((h) => (
              <Headline key={h.id} h={h} tag={h.adapted ? "adapted" : "continues"} />
            ))}
          </div>
        </Section>
      ) : null}
      {facts.length > 0 ? (
        <Section title="What it established">
          <ul className="space-y-1.5">
            {facts.map((f, i) => (
              <li key={i} className="text-[15px] leading-5 text-x-text">
                {f}
              </li>
            ))}
          </ul>
        </Section>
      ) : null}
    </div>
  );
}
